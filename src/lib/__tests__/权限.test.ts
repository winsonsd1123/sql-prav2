import { describe, expect, it } from "vitest";
import { 权限点常量, 汇总权限点, 持有权限, 空权限集合 } from "@/lib/权限";

describe("权限点判定（多角色并集，ADR-0005）", () => {
  it("权限点常量含「随时查看参考答案」与三个占位（编辑题库/安排练习/查看学情）", () => {
    expect(权限点常量.随时查看参考答案).toBe("随时查看参考答案");
    expect(权限点常量.编辑题库).toBe("编辑题库");
    expect(权限点常量.安排练习).toBe("安排练习");
    expect(权限点常量.查看学情).toBe("查看学情");
  });

  it("多角色权限取并集：学生+助教 → 助教的「随时查看参考答案」并入", () => {
    const 学生权限: string[] = [];
    const 助教权限 = [权限点常量.随时查看参考答案];
    const 集合 = 汇总权限点([学生权限, 助教权限]);
    expect(持有权限(集合, 权限点常量.随时查看参考答案)).toBe(true);
  });

  it("任一角色持有即放行（并集语义，不要求全部角色）", () => {
    const 集合 = 汇总权限点([[], [权限点常量.随时查看参考答案], []]);
    expect(持有权限(集合, 权限点常量.随时查看参考答案)).toBe(true);
  });

  it("无角色 → 空集合，任何权限点（含占位）都不放行（安全默认：走摩擦力）", () => {
    const 集合 = 汇总权限点([]);
    expect(集合.size).toBe(0);
    for (const 点 of Object.values(权限点常量)) {
      expect(持有权限(集合, 点)).toBe(false);
    }
  });

  it("重复权限点（多角色挂同一权限点）不放大集合", () => {
    const 单角色 = 汇总权限点([[权限点常量.随时查看参考答案]]);
    const 重复 = 汇总权限点([
      [权限点常量.随时查看参考答案],
      [权限点常量.随时查看参考答案, 权限点常量.随时查看参考答案],
    ]);
    expect(重复.size).toBe(1);
    expect(持有权限(重复, 权限点常量.随时查看参考答案)).toBe(true);
    expect(重复).toEqual(单角色);
  });

  it("占位权限点（编辑题库等）未挂角色时不可凭空持有；挂上后按数据放行", () => {
    const 未挂 = 汇总权限点([[], []]);
    expect(持有权限(未挂, 权限点常量.编辑题库)).toBe(false);
    const 挂上 = 汇总权限点([[权限点常量.编辑题库, 权限点常量.查看学情]]);
    expect(持有权限(挂上, 权限点常量.编辑题库)).toBe(true);
    expect(持有权限(挂上, 权限点常量.查看学情)).toBe(true);
    expect(持有权限(挂上, 权限点常量.安排练习)).toBe(false);
  });

  it("未知权限点（未命名进常量的）不因集合非空而误判持有", () => {
    const 集合 = 汇总权限点([[权限点常量.随时查看参考答案]]);
    expect(持有权限(集合, "不存在的权限点")).toBe(false);
  });

  it("空权限集合常量：数组与 Set 两种入参形态判定一致", () => {
    expect(空权限集合.size).toBe(0);
    expect(持有权限([], 权限点常量.随时查看参考答案)).toBe(false);
    expect(持有权限(空权限集合, 权限点常量.随时查看参考答案)).toBe(false);
  });
});
