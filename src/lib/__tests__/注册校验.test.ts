import { describe, expect, it } from "vitest";
import { 解析登录标识, 校验注册表单 } from "@/lib/注册校验";

const 合法白名单 = { 放开任意域名: false, 域名清单: ["cuc.edu.cn"] };

const 合法表单 = {
  学号: "2022110001",
  姓名: "张三",
  昵称: "小张",
  邮箱: "zhang@cuc.edu.cn",
  密码: "sql2026play",
};

describe("注册表单校验", () => {
  it("全部合法：无任何错误", () => {
    expect(校验注册表单(合法表单, 合法白名单)).toEqual({});
  });

  describe("学号", () => {
    it("为空：提示必填", () => {
      expect(校验注册表单({ ...合法表单, 学号: "" }, 合法白名单).学号).toContain("学号");
    });

    it("含非字母数字字符：提示仅字母数字", () => {
      expect(校验注册表单({ ...合法表单, 学号: "2022 110" }, 合法白名单).学号).toBeTruthy();
      expect(校验注册表单({ ...合法表单, 学号: "2022-110" }, 合法白名单).学号).toBeTruthy();
    });

    it("过短/过长：提示长度范围（4-20 位）", () => {
      expect(校验注册表单({ ...合法表单, 学号: "123" }, 合法白名单).学号).toBeTruthy();
      expect(校验注册表单({ ...合法表单, 学号: "1".repeat(21) }, 合法白名单).学号).toBeTruthy();
    });
  });

  describe("姓名与昵称", () => {
    it("姓名为空：提示必填", () => {
      expect(校验注册表单({ ...合法表单, 姓名: " " }, 合法白名单).姓名).toBeTruthy();
    });

    it("昵称为空：提示必填", () => {
      expect(校验注册表单({ ...合法表单, 昵称: "" }, 合法白名单).昵称).toBeTruthy();
    });

    it("昵称超过 20 字：提示过长", () => {
      expect(校验注册表单({ ...合法表单, 昵称: "一".repeat(21) }, 合法白名单).昵称).toBeTruthy();
      expect(校验注册表单({ ...合法表单, 昵称: "一".repeat(20) }, 合法白名单).昵称).toBeUndefined();
    });
  });

  describe("邮箱", () => {
    it("格式非法：提示格式不正确（不触及白名单）", () => {
      const 错误 = 校验注册表单({ ...合法表单, 邮箱: "zhang.cuc.edu.cn" }, 合法白名单).邮箱;
      expect(错误).toBe("邮箱格式不正确");
    });

    it("域名不在白名单：提示白名单拦截", () => {
      const 错误 = 校验注册表单({ ...合法表单, 邮箱: "zhang@gmail.com" }, 合法白名单).邮箱;
      expect(错误).toContain("白名单");
    });

    it("域名不在白名单但开关打开：不报错", () => {
      const 打开 = { 放开任意域名: true, 域名清单: ["cuc.edu.cn"] };
      expect(校验注册表单({ ...合法表单, 邮箱: "zhang@gmail.com" }, 打开).邮箱).toBeUndefined();
    });
  });

  describe("密码", () => {
    it("不足 8 位：提示长度", () => {
      expect(校验注册表单({ ...合法表单, 密码: "a1b2c3d" }, 合法白名单).密码).toBeTruthy();
    });

    it("纯数字 / 纯字母：提示强度不足（须同时含字母与数字）", () => {
      expect(校验注册表单({ ...合法表单, 密码: "12345678" }, 合法白名单).密码).toBeTruthy();
      expect(校验注册表单({ ...合法表单, 密码: "abcdefgh" }, 合法白名单).密码).toBeTruthy();
    });

    it("8 位以上且含字母与数字：通过", () => {
      expect(校验注册表单({ ...合法表单, 密码: "play2026" }, 合法白名单).密码).toBeUndefined();
    });
  });

  it("多字段同时非法：逐字段给出错误（字段名 → 中文提示）", () => {
    const 错误 = 校验注册表单(
      { 学号: "", 姓名: "", 昵称: "", 邮箱: "x", 密码: "1" },
      合法白名单,
    );
    expect(Object.keys(错误)).toEqual(["学号", "姓名", "昵称", "邮箱", "密码"]);
    // 每条提示都是非空中文文案
    for (const 提示 of Object.values(错误)) expect(提示!.length).toBeGreaterThan(0);
  });
});

describe("登录标识解析", () => {
  it("纯数字：判为学号", () => {
    expect(解析登录标识("2022110001")).toEqual({ 类型: "学号", 值: "2022110001" });
  });

  it("含 @：判为邮箱", () => {
    expect(解析登录标识("zhang@cuc.edu.cn")).toEqual({ 类型: "邮箱", 值: "zhang@cuc.edu.cn" });
  });

  it("字母数字学号格式：判为学号", () => {
    expect(解析登录标识("s2022110001")).toEqual({ 类型: "学号", 值: "s2022110001" });
  });

  it("首尾空白：去除后再判定", () => {
    expect(解析登录标识("  2022110001 \n")).toEqual({ 类型: "学号", 值: "2022110001" });
    expect(解析登录标识(" zhang@cuc.edu.cn ")).toEqual({ 类型: "邮箱", 值: "zhang@cuc.edu.cn" });
  });

  it("空输入：判为无效并给原因", () => {
    const 结果 = 解析登录标识("   ");
    expect(结果.类型).toBe("无效");
    if (结果.类型 === "无效") expect(结果.原因).toBeTruthy();
  });

  it("含非法字符且不含 @（如带空格/连字符）：判为无效", () => {
    expect(解析登录标识("2022 110").类型).toBe("无效");
    expect(解析登录标识("2022-110").类型).toBe("无效");
  });

  it("仅 @ 无域名：判为无效（不是合法邮箱）", () => {
    expect(解析登录标识("zhang@").类型).toBe("无效");
    expect(解析登录标识("@cuc.edu.cn").类型).toBe("无效");
  });

  it("超长学号格式（>20 位）：判为无效", () => {
    expect(解析登录标识("2".repeat(21)).类型).toBe("无效");
  });
});
