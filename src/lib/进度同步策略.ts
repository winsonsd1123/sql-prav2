// T6 · 进度上云同步策略（issue #28 / spec #22「进度上云」）：
// - 合并进度：本地与云进度按字段并集合并，同键冲突云端为准（云端为准、同键覆盖）；
// - 创建进度节流器：判定后约 3 秒静默窗口，窗口内多次判定压一次云写（节流非防抖：
//   首个判定起算，窗口结束写最新值，不随后续判定顺延）；
// - 同步状态机：断网/失败积压 → 指数退避静默重试 → 恢复在线立即冲写的纯状态转移。
// 全部纯函数/可注入计时器，供单测穷举（不依赖真实云与真实时钟）。

import type { 进度记录 } from "@/components/进度";

/** 并集（数字数组），结果升序去重 */
function 并集(本地: number[], 云端: number[]): number[] {
  return [...new Set([...本地, ...云端])].sort((a, b) => a - b);
}

/**
 * 本地与云进度合并（云端为准、同键覆盖）：字段取并集保互不丢题；
 * 同键冲突取云端值；云端为空记录（无该会话数据）时原样保留本地，不作清空。
 */
export function 合并进度(本地: 进度记录, 云端: 进度记录): 进度记录 {
  const 已看提示: Record<string, number> = { ...本地.已看提示, ...云端.已看提示 };
  const 尝试次数: Record<string, number> = { ...本地.尝试次数, ...云端.尝试次数 };
  // 空对象合并后仍可能残留本地独有条目——这正是并集语义，无需清理
  return {
    已通过题号: 并集(本地.已通过题号, 云端.已通过题号),
    已借助答案题号: 并集(本地.已借助答案题号, 云端.已借助答案题号),
    已看提示,
    尝试次数,
    草稿: { ...本地.草稿, ...云端.草稿 },
  };
}

/**
 * 判定后节流合并写（注入写入函数与窗口以便单测）：
 * 排程 = 收到判定结果（或任何需上云的进度变更），窗口内多次只压一次写；
 * 立即冲写 = 会话结束/页面卸载前把待写值立刻落一次并取消计时。
 */
export function 创建进度节流器(
  写入: (进度: 进度记录) => void,
  节流毫秒 = 3000,
): { 排程: (进度: 进度记录) => void; 立即冲写: () => void } {
  let 待写: 进度记录 | null = null;
  let 计时器: ReturnType<typeof setTimeout> | null = null;
  const 落盘 = () => {
    if (待写 === null) return;
    const 进度 = 待写;
    待写 = null;
    写入(进度);
  };
  return {
    排程: (进度) => {
      待写 = 进度;
      if (计时器 === null) 计时器 = setTimeout(() => { 计时器 = null; 落盘(); }, 节流毫秒);
    },
    立即冲写: () => {
      if (计时器 !== null) {
        clearTimeout(计时器);
        计时器 = null;
      }
      落盘();
    },
  };
}

/** 同步阶段：空闲（无待写）/ 待写（节流窗口中）/ 写中（云写进行或待重试触发）/ 积压（写失败待重试） */
export type 同步状态 =
  | { 阶段: "空闲"; 重试次数: number }
  | { 阶段: "待写"; 窗口起点: number; 重试次数: number }
  | { 阶段: "写中"; 重试次数: number }
  | { 阶段: "积压"; 重试次数: number; 下次重试: number };

export type 同步事件 =
  | { 类型: "判定写入"; 时刻: number }
  | { 类型: "节流到期"; 时刻: number }
  | { 类型: "重试时刻到" }
  | { 类型: "写成功" }
  | { 类型: "写失败"; 时刻: number }
  | { 类型: "恢复在线"; 时刻: number };

/** 状态机对调用方的副作用指令：安排 3 秒节流计时 / 按退避安排重试计时 */
export type 同步动作 = "无" | "安排节流写" | "安排重试";

export function 初始同步状态(): 同步状态 {
  return { 阶段: "空闲", 重试次数: 0 };
}

/** 指数退避：3s → 6s → 12s … 封顶 15s（静默重试不弹 UI，e2e 可等待） */
export function 重试退避毫秒(重试次数: number): number {
  return Math.min(3000 * 2 ** (重试次数 - 1), 15_000);
}

/**
 * 同步状态机（纯转移函数）：判定写入只从 空闲 起窗（待写中不重开、积压中并入载荷）；
 * 节流到期/重试时刻到/恢复在线（积压时）转 写中；写成功清积压回空闲，写失败转积压并
 * 按指数退避安排重试。动作由调用方执行副作用（真实计时器与云写）。
 */
export function 同步状态机(状态: 同步状态, 事件: 同步事件): [同步状态, 同步动作] {
  switch (事件.类型) {
    case "判定写入": {
      if (状态.阶段 === "空闲")
        return [{ 阶段: "待写", 窗口起点: 事件.时刻, 重试次数: 状态.重试次数 }, "安排节流写"];
      return [状态, "无"];
    }
    case "节流到期": {
      if (状态.阶段 !== "待写") return [状态, "无"];
      return [{ 阶段: "写中", 重试次数: 状态.重试次数 }, "无"];
    }
    case "重试时刻到": {
      if (状态.阶段 !== "积压") return [状态, "无"];
      return [{ 阶段: "写中", 重试次数: 状态.重试次数 }, "无"];
    }
    case "恢复在线": {
      if (状态.阶段 !== "积压") return [状态, "无"];
      return [{ 阶段: "写中", 重试次数: 状态.重试次数 }, "无"];
    }
    case "写成功":
      return [{ 阶段: "空闲", 重试次数: 0 }, "无"];
    case "写失败": {
      // 写成功清零，故 写中 保留的 重试次数 +1 即累计重试次数
      const 重试次数 = 状态.重试次数 + 1;
      return [
        { 阶段: "积压", 重试次数, 下次重试: 事件.时刻 + 重试退避毫秒(重试次数) },
        "安排重试",
      ];
    }
  }
}
