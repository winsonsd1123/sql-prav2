import type { 域包, 会话, 题目实例 } from "./types";
import { 生成 } from "./generate";
import { 创建随机源 } from "./prng";

/** 会话内题目推进的知识点顺序（GLOSSARY「知识点」：会话按此顺序推进抽题） */
export const 知识点顺序 = [
  "单表查询与投影",
  "条件筛选与排序",
  "聚合与分组",
  "多表 JOIN",
  "子查询",
  "日期函数",
  "综合应用",
] as const;

/**
 * 会话按知识点出题（issue #8 / T7，判题内核纯函数）：
 * 种子 + 域包 → 会话（库与 生成(种子, 域包) 完全一致，题目为按七知识点顺序抽取的 8-12 题）。
 *
 * 抽题规则（同种子确定性）：
 * 1. 题量由种子驱动在 8-12 之间取定；
 * 2. 每个知识点保底 1 题，剩余名额按种子随机分配给还有余量的知识点
 *    （单知识点至多出满其模板数）；
 * 3. 每个知识点的候选模板按种子洗牌后按配额取前若干题，再按知识点顺序拼接，
 *    保证题目按知识点顺序推进、每个知识点至少一题、同知识点内不重复模板。
 */
export function 生成练习会话(种子: number, 域包: 域包): 会话 {
  const 随机 = 创建随机源(种子);
  const 题数 = 随机.整数(8, 12);
  const 会话 = 生成(种子, 域包);

  const 分区 = 知识点顺序.map((知识点) => {
    const 候选 = 会话.题目.filter((q) => q.知识点 === 知识点);
    if (候选.length === 0 && 会话.题目.length > 0) {
      throw new Error(`域包 ${域包.域包ID} 的知识点「${知识点}」没有任何题目模板`);
    }
    return 洗牌(候选, 创建随机源(种子));
  });

  // 配额：每知识点保底 1，剩余名额按种子分配给尚有余量（配额 < 分区大小）的知识点
  const 配额 = 分区.map(() => 1);
  for (let 余 = 题数 - 配额.length; 余 > 0; 余--) {
    const 有余量 = 配额.map((n, i) => (n < 分区[i].length ? i : -1)).filter((i) => i >= 0);
    if (有余量.length === 0) break;
    配额[随机.抽取(有余量)]++;
  }

  const 题目: 题目实例[] = [];
  分区.forEach((候选, i) => {
    题目.push(...候选.slice(0, 配额[i]));
  });
  return { ...会话, 题目 };
}

/** Fisher-Yates 洗牌（种子驱动，确定性） */
function 洗牌<T>(项: readonly T[], 随机: ReturnType<typeof 创建随机源>): T[] {
  const 结果 = [...项];
  for (let i = 结果.length - 1; i > 0; i--) {
    const j = 随机.整数(0, i);
    [结果[i], 结果[j]] = [结果[j], 结果[i]];
  }
  return 结果;
}
