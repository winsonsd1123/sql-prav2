// 大查询防护（issue #10 / T9）：执行超时与结果行数上限的产品级提示。
// 防护提示是演练场产品文案，不走 MySQL 错误三要素映射（非伪造数据库错误）。

/** 单次判题执行的超时上限（毫秒）。超时由主线程终止 Worker 兜底（sql.js 同步执行无法中途取消） */
export const 执行超时毫秒 = 5_000;

/** 学生 SQL / 参考答案任一结果集的行数上限，超过即判定为误写高代价查询 */
export const 结果行数上限 = 10_000;

/** 防护触发（超时 / 行数超限 / 执行环境异常）：以产品提示呈现，message 即 UI 文案 */
export class 防护超限错误 extends Error {
  constructor(
    readonly 种类: "超时" | "行数上限" | "环境异常",
    message: string,
  ) {
    super(message);
    this.name = "防护超限错误";
  }
}

export const 超时提示 = `查询执行超过 ${执行超时毫秒 / 1000} 秒上限，已自动终止。请检查是否缺少 JOIN 连接条件形成笛卡尔积、或过滤条件过宽，修改后重试。`;

export const 行数上限提示 = `查询结果超过 ${结果行数上限} 行上限，已停止执行。请检查是否缺少连接条件产生了笛卡尔积，或先用 LIMIT 约束行数再重试。`;

export const 环境异常提示 = "执行环境异常，已重置数据库引擎，请重试。";
